function [ac,ctx,info] = SilverScytheBuild(fidelity,options)
% SILVERSCYTHEBUILD  Assemble the Silver Scythe AAMF Aircraft object.
%
%   [ac,ctx] = SilverScytheBuild("high");
%   [ac,ctx] = SilverScytheBuild("low");
%
% Follows the same construction order as examples/F16/F16Simp.m: reference
% geometry, frames, mass components, control surfaces, propulsion, then the
% aerodynamic and gravity load sources.
%
% Body frame: origin at fuselage station 30.23 ft, the report's takeoff CG
% (report Table 13), +x forward, +y right, +z down.  Report stations
% increase aft, so a component at station s sits at body
% x = (30.23 - s)*0.3048 m.
%
% Aerodynamic coefficients are referenced to the body origin through a
% fixed "aero_ref" frame, which is what the AeroLoadSolver contract
% requires.  The framework then transfers the aerodynamic moment to the
% instantaneous mass CG, so CG travel from fuel burn is handled by the
% force/moment pipeline instead of being baked into the coefficients.
%
% Control-vector order:
%   1 aileron        2 elevator      3 rudder
%   4 nozzle_pitch   5 nozzle_yaw
%   6 throttle_L     7 throttle_R
%
% "elevator" and "rudder" are the symmetric and differential ruddervator
% commands.  They keep the framework's generic names so the standard trim
% configuration used by the other examples works unchanged; each surface
% records its physical identity in surface_type and metadata.

if nargin < 1 || isempty(fidelity), fidelity = "high"; end
if nargin < 2 || isempty(options), options = struct(); end

ctx = SilverScytheContext(fidelity,options);
ss = ctx.ss;
ft = ss.units.ft_to_m;

ac = Aircraft();
ac.ground_k = ss.sim.ground_k;
ac.ground_c = ss.sim.ground_c;

%% Reference geometry
% The aerodynamic moment reference is the station of whichever published
% derivative source the context selected: 27.9 ft for the report Table 8
% textbook chain, 28.3053 ft for the DATCOM model.  The framework transfers
% the moment from there to the instantaneous mass CG.
aero_ref_x = station_to_body_x(ctx.aero_reference_station_ft,ss.station.cg_ft,ft);

ac.geometry.set_reference_geometry(ss.S_ref,ss.b_ref,ss.cbar);
ac.geometry.set_reference_point([aero_ref_x 0 0]);
ac.geometry.aero_mach_max      = ss.sim.aero_mach_max;
ac.geometry.aero_beta_limit_rad = deg2rad(ss.sim.aero_beta_limit_deg);
ac.geometry.aileron_limit_rad  = deg2rad(ss.controls.aileron.max_deg);
ac.geometry.rudder_limit_rad   = deg2rad(ss.controls.ruddervator.max_deg);

%% Frames
ac.set_body_frame("body");
ac.set_reference_frame("body");

add_or_update_frame(ac,"aero_ref","body",[aero_ref_x;0;0],@(x) eye(3));
add_or_update_frame(ac,"cg","body",[0;0;0],@(x) eye(3));
add_or_update_frame(ac,"gravity_cg","body",[0;0;0],@(x) ned_to_body_dcm(x));

nozzle_x = station_to_body_x(ss.station.nozzle_ft,ss.station.cg_ft,ft);
nozzle_y = ss.engine_y_ft*ft;
add_or_update_frame(ac,"nozzle_L","body",[nozzle_x;-nozzle_y;0],@(x) eye(3));
add_or_update_frame(ac,"nozzle_R","body",[nozzle_x; nozzle_y;0],@(x) eye(3));

%% Mass components, report Tables 12 and 13
add_components(ac,ss);

%% Control surfaces
aileron = ControlSurface("aileron","wing_trailing_edge_differential", ...
    "primary",[1 0 0], ...
    deg2rad(ss.controls.aileron.max_deg), -deg2rad(ss.controls.aileron.max_deg), ...
    ctx.sd.Cl_deltaa,0,ctx.sd.Cn_deltaa);

elevator = ControlSurface("elevator","ruddervator_symmetric","primary", ...
    [0 1 0], ...
    deg2rad(ss.controls.ruddervator.max_deg), -deg2rad(ss.controls.ruddervator.max_deg), ...
    0,ctx.sd.Cm_deltae,0);

rudder = ControlSurface("rudder","ruddervator_differential","primary", ...
    [0 0 1], ...
    deg2rad(ss.controls.ruddervator.max_deg), -deg2rad(ss.controls.ruddervator.max_deg), ...
    ctx.sd.Cl_deltar,0,ctx.sd.Cn_deltar);

% Nozzle channels carry no aerodynamic derivative; the thrust-vector force
% is generated by the propulsive elements.  A null axis keeps the generic
% trim solver from treating them as extra pitch/yaw surfaces while the
% generalized S-function still saturates and rate-limits them.
nozzle_pitch = ControlSurface("nozzle_pitch","thrust_vector_pitch", ...
    "secondary",[0 0 0], ...
    deg2rad(ss.controls.nozzle.max_deg), -deg2rad(ss.controls.nozzle.max_deg), ...
    0,0,0);
nozzle_yaw = ControlSurface("nozzle_yaw","thrust_vector_yaw", ...
    "secondary",[0 0 0], ...
    deg2rad(ss.controls.nozzle.max_deg), -deg2rad(ss.controls.nozzle.max_deg), ...
    0,0,0);

ac.add_control_surface(aileron);
ac.add_control_surface(elevator);
ac.add_control_surface(rudder);
ac.add_control_surface(nozzle_pitch);
ac.add_control_surface(nozzle_yaw);

n_cs = numel(ac.control_surfaces);
idx_nozzle_pitch = 4;
idx_nozzle_yaw   = 5;

%% Propulsion: twin F414-GE-400 with vectoring nozzles
engine_L = SilverScytheVectoringTurbofan("F414_L",ac.get_frame("nozzle_L"), ...
    [1;0;0],ctx.thrust_handle,idx_nozzle_pitch,idx_nozzle_yaw, ...
    deg2rad(ss.controls.nozzle.max_deg),deg2rad(ss.controls.nozzle.max_deg));
engine_R = SilverScytheVectoringTurbofan("F414_R",ac.get_frame("nozzle_R"), ...
    [1;0;0],ctx.thrust_handle,idx_nozzle_pitch,idx_nozzle_yaw, ...
    deg2rad(ss.controls.nozzle.max_deg),deg2rad(ss.controls.nozzle.max_deg));

ac.add_propulsive_element(engine_L);
ac.add_propulsive_element(engine_R);

ac.get_component("engine_left").add_load_source( ...
    PropulsionLoadSolver(engine_L,ac.get_frame("nozzle_L")));
ac.get_component("engine_right").add_load_source( ...
    PropulsionLoadSolver(engine_R,ac.get_frame("nozzle_R")));

%% Aerodynamic and gravity load sources
aero_model = CoefficientAerodynamics( ...
    @(x,u,g) SilverScytheLookup(x,u,g,ctx));
aero_solver = AeroLoadSolver(aero_model,ac.geometry,ac,ac.get_frame("aero_ref"));
gravity_solver = GravityLoadSolver(ac,ac.get_frame("gravity_cg"));

ac.add_load_source(aero_solver);
ac.add_load_source(gravity_solver);

%% Synchronise the CG frames with the mass build-up
[m_total,cg_total,I_total] = ac.compute_total_mass_properties();
ac.update_frame_position("cg",cg_total);
ac.update_frame_position("gravity_cg",cg_total);
ac.set_reference_frame("cg");

cg_station_ft = ss.station.cg_ft - cg_total(1)/ft;

info = struct();
info.fidelity      = ctx.fidelity;
info.mass_kg       = m_total;
info.mass_lb       = m_total/ss.units.lbm_to_kg;
info.cg_body_m     = cg_total;
info.cg_station_ft = cg_station_ft;
info.inertia_kgm2  = I_total;
info.n_cs          = n_cs;
info.n_pe          = numel(ac.propulsive_elements);
info.n_total       = n_cs + numel(ac.propulsive_elements);
info.control_order = ["aileron";"elevator";"rudder";"nozzle_pitch"; ...
                      "nozzle_yaw";"throttle_F414_L";"throttle_F414_R"];
info.aero_reference_station_ft = ctx.aero_reference_station_ft;
info.longitudinal_source = ctx.longitudinal_source;
info.static_margin_at_aero_ref = ctx.sd.static_margin;
info.static_margin_at_cg = (ctx.sd.neutral_point_ft - cg_station_ft)/ss.cbar_ft;
info.report_mass_lb = ss.weights.TOGW_strike_lb;
info.report_cg_station_ft = ss.weights.takeoff_cg_station_ft;

end

% =======================================================================
function add_components(ac,ss)
ft = ss.units.ft_to_m;
for i = 1:size(ss.components,1)
    name       = string(ss.components{i,1});
    weight_lb  = ss.components{i,2};
    station_ft = ss.components{i,3};
    y_ft       = ss.components{i,4};
    z_ft       = ss.components{i,5};
    dims_ft    = ss.components{i,6};
    type       = string(ss.components{i,7});

    m = weight_lb*ss.units.lbm_to_kg;
    r = [station_to_body_x(station_ft,ss.station.cg_ft,ft); y_ft*ft; z_ft*ft];
    dims = dims_ft*ft;
    I = box_inertia(m,dims(1),dims(2),dims(3));

    frame_name = string(matlab.lang.makeValidName(char(name + "_frame")));
    add_or_update_frame(ac,frame_name,"body",r,@(x) eye(3));

    comp = Component(name,m,[0;0;0],I,ac.get_frame(frame_name),type);
    comp.set_metadata("report_station_ft",station_ft);
    comp.set_metadata("weight_lb",weight_lb);
    ac.add_component(comp);
end
end

% =======================================================================
function I = box_inertia(m,L,W,H)
I = diag([(m/12)*(W^2 + H^2), ...
          (m/12)*(L^2 + H^2), ...
          (m/12)*(L^2 + W^2)]);
end

% =======================================================================
function x = station_to_body_x(station_ft,origin_station_ft,ft_to_m)
x = (origin_station_ft - station_ft)*ft_to_m;
end

% =======================================================================
function add_or_update_frame(ac,name,parent,r,dcm_fn)
if ac.has_frame(name)
    ac.update_frame_position(name,r(:));
    ac.update_frame_orientation(name,dcm_fn);
else
    ac.add_frame(name,parent,r(:),dcm_fn);
end
end

% =======================================================================
function C = ned_to_body_dcm(x)
phi = x(7); theta = x(8); psi = x(9);
cp = cos(phi); sp = sin(phi);
ct = cos(theta); st = sin(theta);
cs = cos(psi);  ss_ = sin(psi);
C = [ct*cs,              ct*ss_,             -st; ...
     sp*st*cs - cp*ss_,  sp*st*ss_ + cp*cs,  sp*ct; ...
     cp*st*cs + sp*ss_,  cp*st*ss_ - sp*cs,  cp*ct];
end
